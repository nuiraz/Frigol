import type { Recipe } from '@/lib/types';

import { INGREDIENT_BY_ID } from './ingredients';

type Line = [id: string, quantity?: string, optional?: 'option'];
type Meta = Pick<Recipe, 'time' | 'difficulty' | 'servings' | 'category' | 'tags' | 'description'>;

function r(id: string, title: string, emoji: string, meta: Meta, lines: Line[], steps: string[]): Recipe {
  return {
    id: `l-${id}`,
    source: 'local',
    title,
    emoji,
    ...meta,
    ingredients: lines.map(([ing, quantity, optional]) => ({
      id: ing,
      name: INGREDIENT_BY_ID.get(ing)?.name ?? ing,
      quantity,
      optional: optional === 'option',
    })),
    steps,
  };
}

